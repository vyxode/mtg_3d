/**
 * Spanish printings of every card the engine can play: name, type line, rules text and image, from Scryfall.
 * Writes packages/cards/src/es.ts. Run where Scryfall is reachable (`pnpm cards:es`, or the "Cartas en español"
 * workflow). Cards with no Spanish printing are left out and show in English.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEFS, type EsCard } from '@mtg3d/cards';

const API = 'https://api.scryfall.com';
const HEADERS = { 'User-Agent': 'mtg3d/0.1 (+https://github.com/vyxode/mtg_3d)', Accept: 'application/json;q=0.9,*/*;q=0.8' };
const OUT = fileURLToPath(new URL('../../../packages/cards/src/es.ts', import.meta.url));

interface Face { name: string; printed_name?: string; printed_type_line?: string; printed_text?: string; image_uris?: { normal: string } }
export interface ScryCard extends Face { lang: string; card_faces?: Face[] }

/** One entry per face, keyed by the English face name the engine uses. */
export function entriesOf(card: ScryCard): [string, EsCard][] {
  const faces = card.card_faces?.length ? card.card_faces : [card];
  return faces.map((f) => [f.name, {
    name: f.printed_name ?? f.name,
    type: f.printed_type_line ?? '',
    text: f.printed_text ?? '',
    image: f.image_uris?.normal ?? card.image_uris?.normal ?? null,
  }]);
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const pause = () => sleep(600); // card searches are rate-limited more tightly than other endpoints

async function spanish(name: string, token: boolean, attempt = 1): Promise<ScryCard | null> {
  const q = `!"${name}" lang:es${token ? ' is:token' : ''}`;
  const res = await fetch(`${API}/cards/search?q=${encodeURIComponent(q)}&unique=prints&order=released&dir=desc&include_extras=${String(token)}`, { headers: HEADERS });
  if (res.status === 429 && attempt < 5) { // too many requests: wait as asked, then try again
    await sleep(Number(res.headers.get('retry-after') ?? '0') * 1000 || 2000 * attempt);
    return spanish(name, token, attempt + 1);
  }
  if (res.status === 404) return null; // no Spanish printing
  if (!res.ok) throw new Error(`${name}: HTTP ${String(res.status)}`);
  const body = (await res.json()) as { data: ScryCard[] };
  // Newest Spanish printing whose name is actually printed in Spanish (some entries only carry the English data).
  const translated = (c: ScryCard) => !!(c.printed_name ?? c.card_faces?.[0]?.printed_name);
  return body.data.find((c) => c.lang === 'es' && translated(c)) ?? body.data.find((c) => c.lang === 'es') ?? null;
}

async function main(): Promise<void> {
  const out: Record<string, EsCard> = {};
  const missing: string[] = [];
  for (const def of DEFS) {
    if (def.frontFace || out[def.name]) continue; // back faces come with their front
    await pause();
    const card = await spanish(def.name, !!def.token);
    if (!card) { missing.push(def.name); continue; }
    for (const [k, v] of entriesOf(card)) out[k] = v;
  }
  const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
  const body = JSON.stringify(sorted, null, 2);
  writeFileSync(OUT, `// Generated by apps/server/src/es-cards.ts from Scryfall's Spanish printings: do not edit by hand.\nimport type { EsCard } from './i18n';\n\nexport const ES: Record<string, EsCard> = ${body};\n`);
  console.log(`${String(Object.keys(out).length)} faces in Spanish; without a Spanish printing: ${missing.join(', ') || 'none'}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
