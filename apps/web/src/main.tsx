import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { registerCards, registerSpanish, type EsCard } from '@mtg3d/cards';
import type { CardDef } from '@mtg3d/engine';
import { App } from './App';
// Self-hosted (no request to a font service): Alegreya for names and numbers, Alegreya Sans for the interface.
import '@fontsource/alegreya/latin-400.css';
import '@fontsource/alegreya/latin-400-italic.css';
import '@fontsource/alegreya/latin-700.css';
import '@fontsource/alegreya-sans/latin-400.css';
import '@fontsource/alegreya-sans/latin-500.css';
import '@fontsource/alegreya-sans/latin-700.css';
import './styles.css';

// Every card the engine can play from its Oracle data (generated by the "Cartas de Magic" workflow); without it, only
// the hand-written cards are available.
// Their Spanish printings come in es.json (same workflow); both load in parallel.
const load = async (file: string, use: (data: unknown) => void) => {
  try {
    const r = await fetch(`${import.meta.env.BASE_URL}${file}`);
    if (r.ok) use(await r.json());
  } catch { /* offline or not generated yet */ }
};
await Promise.all([
  load('oracle.json', (d) => { registerCards((d as { defs: CardDef[] }).defs); }),
  load('es.json', (d) => { registerSpanish(d as Record<string, EsCard>); }),
]);

createRoot(document.getElementById('root') as HTMLElement).render(<StrictMode><App /></StrictMode>);
